#!/usr/bin/env node
// Dev-only vendoring script (not part of the app bundle).
//
// Converts the VocabKitchen-CLI word-list artifacts into the TS data modules
// the app imports:
//   - src/data/cefrLevels.ts        (word -> CEFR level, from WordLists/CEFR/levels.json)
//   - src/data/academicWordLists.ts (AWL + NAWL surface forms)
//
// Usage:
//   node scripts/build-cefr-index.mjs [path-to-vocabkitchen-cli]
//   VOCABKITCHEN_DIR=/path/to/vocabkitchen-cli node scripts/build-cefr-index.mjs
//
// Re-run when VocabKitchen updates its lists, then record the new source commit
// SHA in docs/VOCAB_WORDLISTS_PROVENANCE.md. The generated files are checked in
// (same posture as the previously hand-maintained src/data/cefrjVocabulary.ts).

import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = fileURLToPath(new URL('.', import.meta.url));
const repoRoot = resolve(scriptDir, '..');
const srcDir = process.argv[2] || process.env.VOCABKITCHEN_DIR || resolve(repoRoot, '../vocabkitchen-cli');

const VALID_LEVELS = new Set(['A1', 'A2', 'B1', 'B2', 'C1', 'C2']);

function readLines(path) {
    return readFileSync(path, 'utf8')
        .split('\n')
        .map((l) => l.trim().toLowerCase())
        .filter(Boolean);
}

function uniqueSorted(words) {
    return [...new Set(words)].sort();
}

function buildCefrLevels() {
    const raw = JSON.parse(readFileSync(join(srcDir, 'WordLists/CEFR/levels.json'), 'utf8'));
    const words = raw.words ?? {};
    const entries = [];
    for (const [word, meta] of Object.entries(words)) {
        const level = meta?.level;
        if (!VALID_LEVELS.has(level)) continue;
        entries.push([word.toLowerCase(), level]);
    }
    entries.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

    const body = entries.map(([w, l]) => `    [${JSON.stringify(w)}, '${l}'],`).join('\n');
    const header = `// CEFR vocabulary index (A1–C2) — word -> CEFR level.
//
// GENERATED by scripts/build-cefr-index.mjs from VocabKitchen-CLI
// (WordLists/CEFR/levels.json). Do not edit by hand — re-run the script.
// Provenance, sources, and licences: docs/VOCAB_WORDLISTS_PROVENANCE.md.
//
// Sources: Words-CEFR-Dataset (MIT) gap-filled with the OLP-EN-CEFRJ profiles
// (CEFR-J A1–B2 © Tono Laboratory, TUFS; Octanove C1/C2). Cite CEFR-J per the
// provenance doc. Lists are pre-expanded to inflected surface forms, so the
// profiler matches exact lowercased surface forms (no lemmatisation).
//
// A Map (not a plain object) so keys like "constructor"/"toString" can't collide
// with Object.prototype — a plain-object index would return an inherited function
// for those words instead of undefined.

import type { CefrLevel } from '../types';

export const CEFR_WORD_LEVELS: ReadonlyMap<string, CefrLevel> = new Map<string, CefrLevel>([
${body}
]);
`;
    writeFileSync(join(repoRoot, 'src/data/cefrLevels.ts'), header);
    return entries.length;
}

function buildAcademicLists() {
    const awl = uniqueSorted(readLines(join(srcDir, 'WordLists/AWL/awl.txt')));
    const nawl = uniqueSorted(readLines(join(srcDir, 'WordLists/NAWL/nawl.txt')));

    const arr = (name, words) =>
        `export const ${name}: readonly string[] = [\n${words.map((w) => `    ${JSON.stringify(w)},`).join('\n')}\n];`;

    const out = `// Academic Word Lists — AWL (Coxhead) + NAWL (Browne, Culligan & Phillips).
//
// GENERATED by scripts/build-cefr-index.mjs from VocabKitchen-CLI
// (WordLists/AWL/awl.txt, WordLists/NAWL/nawl.txt). Do not edit by hand.
// Provenance and licences: docs/VOCAB_WORDLISTS_PROVENANCE.md.

${arr('AWL_WORDS', awl)}

${arr('NAWL_WORDS', nawl)}
`;
    writeFileSync(join(repoRoot, 'src/data/academicWordLists.ts'), out);
    return { awl: awl.length, nawl: nawl.length };
}

const levelCount = buildCefrLevels();
const academic = buildAcademicLists();
console.log(`cefrLevels.ts: ${levelCount} words`);
console.log(`academicWordLists.ts: AWL ${academic.awl}, NAWL ${academic.nawl}`);
