import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { DEFAULT_FORMAT } from '../types';
import type { Rubric, Student, StudentRubric } from '../types';
import { buildRubricHTML } from './pdfExport';
import i18n, { i18nReady } from '../i18n';
import nlResources from '../locales/nl.json';

// pdfExport.ts's docLabel() reuses docxExport.ts's `exportDoc.*` keys via a bare `import i18n
// from 'i18next'` — the same configured singleton the rest of the app uses once `src/i18n.ts`
// has run, but nothing in that module itself guarantees the EN bundle is loaded. Import the
// app's own i18n module here (as a real page/component would) so this test exercises the real
// translated text rather than an uninitialized i18next instance silently rendering "undefined".
function fixtures() {
    const level = { id: 'l1', label: 'Good', minPoints: 3, maxPoints: 3, description: 'Solid', subItems: [] };
    const rubric = {
        id: 'r1',
        name: 'Essay',
        subject: 'English',
        description: '',
        criteria: [{ id: 'c1', title: 'Writing', description: '', weight: 50, levels: [level] }],
        gradeScaleId: 'letter-10',
        format: { ...DEFAULT_FORMAT, showWeights: true, showPoints: true },
        attachmentIds: [],
        createdAt: '2026-01-01T00:00:00.000Z',
        updatedAt: '2026-01-01T00:00:00.000Z',
        totalMaxPoints: 3,
        scoringMode: 'weighted-percentage',
    } as unknown as Rubric;
    const student = { id: 's1', name: 'Alice', classId: 'k1' } as Student;
    const sr = {
        id: 'sr1',
        rubricId: 'r1',
        studentId: 's1',
        entries: [{ criterionId: 'c1', levelId: 'l1', comment: '', checkedSubItems: [] }],
        overallComment: 'Great work',
        isPeerReview: true,
        gradedAt: '2026-01-02T00:00:00.000Z',
        globalModifier: { type: 'points', value: 1, reason: 'bonus' },
    } as unknown as StudentRubric;
    return { rubric, student, sr };
}

describe('buildRubricHTML labels (#960)', () => {
    beforeAll(async () => {
        await i18nReady;
        await i18n.changeLanguage('en');
    });
    afterAll(async () => {
        await i18n.changeLanguage('en');
    });

    it('renders every label through i18next instead of hardcoded English', () => {
        const { rubric, student, sr } = fixtures();
        const html = buildRubricHTML(sr, rubric, student, null);

        expect(html).not.toContain('undefined');
        expect(html).toContain('Student:');
        expect(html).toContain('Graded:');
        expect(html).toContain('Weight: 50%');
        expect(html).toContain('3 pts');
        expect(html).toContain('Modifier:');
        expect(html).toContain('Overall comment:');
        expect(html).toContain('Generated by Rubric Maker');
        expect(html).toContain('Peer Review');
        expect(html).toContain('Criterion');
    });

    it('switches to the active i18next language instead of staying English', async () => {
        // `src/i18n.ts` lazy-loads non-English bundles on a fire-and-forget 'languageChanged'
        // listener; add the bundle directly so the translated text is there as soon as
        // changeLanguage resolves, rather than racing that background import.
        if (!i18n.hasResourceBundle('nl', 'translation')) {
            i18n.addResourceBundle('nl', 'translation', nlResources);
        }
        await i18n.changeLanguage('nl');
        const { rubric, student, sr } = fixtures();
        const html = buildRubricHTML(sr, rubric, student, null);

        expect(html).not.toContain('undefined');
        expect(html).toContain('Leerling:');
        expect(html).toContain('Beoordeeld:');
        expect(html).toContain('Gegenereerd door Rubric Maker');
    });

    it('shows "not yet graded" instead of a bare N/A when there is no graded date', async () => {
        await i18n.changeLanguage('en');
        const { rubric, student, sr } = fixtures();
        const html = buildRubricHTML({ ...sr, gradedAt: '' }, rubric, student, null);
        expect(html).toContain('Not yet graded');
        expect(html).not.toContain('N/A');
    });

    it('localizes the point-modifier unit instead of a hardcoded "pts" (CodeRabbit #969)', async () => {
        if (!i18n.hasResourceBundle('nl', 'translation')) {
            i18n.addResourceBundle('nl', 'translation', nlResources);
        }
        await i18n.changeLanguage('nl');
        const { rubric, student, sr } = fixtures();
        const html = buildRubricHTML(sr, rubric, student, null);

        expect(html).toContain('+1 ptn');
        expect(html).not.toContain('pts');
    });

    it('keeps "%" literal for a percentage modifier rather than routing it through exportDoc.points', async () => {
        await i18n.changeLanguage('en');
        const { rubric, student, sr } = fixtures();
        const html = buildRubricHTML(
            { ...sr, globalModifier: { type: 'percentage', value: 5, reason: 'bonus' } },
            rubric,
            student,
            null
        );

        expect(html).toContain('+5%');
    });
});
